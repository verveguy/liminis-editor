#!/usr/bin/env node
/**
 * Generate `examples/demo/src/docs-content.generated.js` from the root
 * `README.md`.
 *
 * The demo's Documentation tab (verveguy/liminis-editor#3, FR-005–FR-009)
 * renders this README verbatim rather than a second, hand-authored copy of
 * the same exports/peer-deps/sideEffects/versioning/annotations content —
 * one copy, covered by `tests/adr-citations.test.ts`, that stays in sync by
 * construction instead of by discipline. Mirrors the codegen pattern
 * `scripts/generate-demo-fixtures.mjs` established for the fixture corpus
 * (docs/decisions/adr-081.md).
 *
 * The generated file is gitignored — `pnpm demo`, `scripts/build-examples.mjs`
 * and `scripts/build-site.mjs` all run this script first, so there is no code
 * path that consumes a stale copy.
 *
 * Usage: `node scripts/generate-demo-docs.mjs`
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const README_PATH = resolve(REPO_ROOT, 'README.md')
const OUT_FILE = resolve(REPO_ROOT, 'examples', 'demo', 'src', 'docs-content.generated.js')

const readme = readFileSync(README_PATH, 'utf8')

const banner = `// Generated by scripts/generate-demo-docs.mjs from the repository root
// README.md. Do not edit by hand — this file is gitignored and regenerated on
// every \`pnpm demo\` / \`pnpm build:examples\` / \`pnpm build:site\` run.
`

const body = `export const readme = ${JSON.stringify(readme)}\n`

mkdirSync(dirname(OUT_FILE), { recursive: true })
writeFileSync(OUT_FILE, banner + body)

console.log(`Wrote README.md content to ${OUT_FILE}`)
